#!/usr/bin/env python3
"""
Scrapes the Redline site's own pages (filings/*.html, topics/*.html) to
build search-data.js for the search.html page. Does not invent any
content - pulls titles, dates, status, and company straight from each
filing page's own <title> tag, and topics from the topic hub pages that
already group filings by topic.

Run from inside the redline project folder:
    python3 build_search_index.py

Writes: search-data.js
Prints a report so you can sanity-check the result before deploying.
"""
import re
import os
import glob
import json
import html

TITLE_RE = re.compile(r"<title>(.*?)</title>", re.DOTALL)
CANONICAL_RE = re.compile(r'<link rel="canonical" href="([^"]+)"')
STAMP_RE = re.compile(r'class="stamp( partial)?"[^>]*>\s*([^<]+?)\s*<', re.DOTALL)
DATE_RE = re.compile(r"\b([A-Z][a-z]+\.?\s+\d{1,2},\s+20\d{2})\b")
FILING_LINK_RE = re.compile(r'href="[^"]*filings/([a-zA-Z0-9\-]+)\.html"')
H1_RE = re.compile(r"<h1[^>]*>(.*?)</h1>", re.DOTALL)

# Ordered longest/most-specific first, so "PayPal–Venmo" is checked
# before the plain "PayPal" prefix it would otherwise also match.
COMPANY_PREFIXES = [
    ("PayPal–Venmo", "PayPal"),
    ("Google Ads", "Google Ads"),
    ("Best Buy", "Best Buy"),
    ("T-Mobile", "T-Mobile"),
    ("GitHub", "GitHub"),
    ("DoorDash", "DoorDash"),
    ("LinkedIn", "LinkedIn"),
    ("Starlink", "Starlink"),
    ("Discord", "Discord"),
    ("Reddit", "Reddit"),
    ("Target", "Target"),
    ("Adobe", "Adobe"),
    ("PayPal", "PayPal"),
]


def strip_tags(s):
    return re.sub(r"<[^>]+>", "", s).strip()


def clean(raw):
    return html.unescape(strip_tags(raw)).strip()


def split_title(raw_title):
    """
    raw_title looks like:
      "Adobe General Terms Replaced: AI &amp; Liability — Redline"
      "DoorDash 'Spotlight' Ad Replaces Banners — Redline App Watch"
    Returns (company, headline, category).
    """
    t = clean(raw_title)
    # strip the trailing site suffix, keeping track of whether it's an
    # App Watch report or a regular ToS/Privacy filing
    category = "App Watch" if t.endswith("Redline App Watch") else "ToS/Privacy"
    t = re.sub(r"\s*—\s*Redline(\s+App Watch)?\s*$", "", t).strip()

    for prefix, company in COMPANY_PREFIXES:
        if t.startswith(prefix):
            headline = t[len(prefix):].strip(" :—-")
            return company, headline, category

    return "", t, category


def page_name(path):
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    m = TITLE_RE.search(content)
    if m:
        name = clean(m.group(1))
        name = re.sub(r"\s*[—|]\s*.*$", "", name).strip()
        return name
    m = H1_RE.search(content)
    if m:
        return clean(m.group(1))
    return os.path.splitext(os.path.basename(path))[0].replace("-", " ").title()


def build_topic_map():
    """Maps filing slug -> list of topic display names, from topic hub pages."""
    mapping = {}
    for path in sorted(glob.glob("topics/*.html")):
        if os.path.basename(path) == "topics.html":
            continue
        name = page_name(path)
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        for slug in FILING_LINK_RE.findall(content):
            mapping.setdefault(slug, []).append(name)
    return mapping


def main():
    if not os.path.isdir("filings"):
        print("ERROR: run this from the redline project root (no 'filings' folder found here).")
        return

    topic_map = build_topic_map()

    entries = []
    missing_company = []
    missing_date = []
    missing_status = []

    for path in sorted(glob.glob("filings/*.html")):
        slug = os.path.splitext(os.path.basename(path))[0]
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()

        m = TITLE_RE.search(content)
        raw_title = m.group(1) if m else slug
        company, headline, category = split_title(raw_title)
        if not company:
            missing_company.append(slug)

        m = CANONICAL_RE.search(content)
        rel_url = f"filings/{slug}.html"

        m = STAMP_RE.search(content)
        if m:
            status = "Partially Verified" if m.group(1) else "Verified"
        else:
            status = ""
            missing_status.append(slug)

        m = DATE_RE.search(content)
        date = m.group(1) if m else ""
        if not date:
            missing_date.append(slug)

        topics = topic_map.get(slug, [])

        entries.append({
            "slug": slug,
            "company": company,
            "title": headline,
            "category": category,
            "date": date,
            "status": status,
            "topics": topics,
            "url": rel_url,
        })

    with open("search-data.js", "w", encoding="utf-8") as f:
        f.write("// Auto-generated by build_search_index.py - do not hand-edit.\n")
        f.write("const SEARCH_INDEX = ")
        f.write(json.dumps(entries, indent=2, ensure_ascii=False))
        f.write(";\n")

    print(f"Wrote search-data.js with {len(entries)} filings.\n")

    companies_found = sorted(set(e["company"] for e in entries if e["company"]))
    print(f"Companies found: {len(companies_found)}")
    for c in companies_found:
        print(f"  {c}")
    print()

    if missing_company:
        print(f"No company matched for {len(missing_company)} filing(s):")
        for s in missing_company:
            print(f"  {s}")
        print()

    if missing_date:
        print(f"No date detected for {len(missing_date)} filing(s):")
        for s in missing_date:
            print(f"  {s}")
        print()

    if missing_status:
        print(f"No status stamp detected for {len(missing_status)} filing(s):")
        for s in missing_status:
            print(f"  {s}")
        print()

    print("Sample entries:")
    for e in entries[:3]:
        print(json.dumps(e, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
